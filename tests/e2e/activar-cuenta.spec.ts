import { test, expect } from './fixture'
test('la invitación usa el fragmento, el paciente elige contraseña y no se consume con solo abrirla', async ({ page }) => {
  const llamadas: any[] = [], secreto = 'a'.repeat(64)
  await page.route('**/api/portal/activacion', r => {
    const b = r.request().postDataJSON(); llamadas.push(b)
    return r.fulfill({ json: b.accion === 'verificar' ? { nombre: 'Paciente de prueba', correo: 'paciente@example.test', activada: false } : { activada: true } })
  })
  await page.goto('/activar-cuenta#' + secreto)
  await expect(page.getByText('paciente@example.test', { exact: true })).toBeVisible()
  expect(page.url()).not.toContain(secreto); expect(llamadas).toHaveLength(1)
  await page.getByLabel('Contraseña', { exact: true }).fill('MiCuentaSegura123')
  await page.getByLabel('Confirmar contraseña').fill('OtraClaveSegura123')
  await page.getByRole('button', { name: 'Activar mi cuenta' }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('no coinciden'); expect(llamadas).toHaveLength(1)
  await page.getByLabel('Confirmar contraseña').fill('MiCuentaSegura123')
  await page.screenshot({ path: '.herramientas/activar-cuenta.png', fullPage: true })
  await page.getByRole('button', { name: 'Activar mi cuenta' }).click()
  await expect(page.getByRole('heading', { name: 'Tu cuenta está activada' })).toBeVisible()
  expect(llamadas[1]).toMatchObject({ accion: 'activar', token: secreto, nueva: 'MiCuentaSegura123' })
})
test('un enlace vencido muestra cómo pedir otro y no permite elegir contraseña', async ({ page }) => {
  await page.route('**/api/portal/activacion', r => r.fulfill({ status: 400, json: { error: 'El enlace es inválido o venció. Solicita otra invitación a recepción.' } }))
  await page.goto('/activar-cuenta#' + 'b'.repeat(64))
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Solicita otra invitación a recepción')
  await expect(page.locator('input[type=password]')).toHaveCount(0)
})
test('la activación se adapta al teléfono y conserva la contraseña ante un fallo temporal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/api/portal/activacion', r => r.request().postDataJSON().accion === 'verificar' ? r.fulfill({ json: { nombre: 'Paciente de prueba', correo: 'paciente@example.test' } }) : r.fulfill({ status: 409, json: { error: 'No se pudo activar la cuenta.' } }))
  await page.goto('/activar-cuenta#' + 'c'.repeat(64))
  await page.getByLabel('Contraseña', { exact: true }).fill('MiCuentaSegura123')
  await page.getByLabel('Confirmar contraseña').fill('MiCuentaSegura123')
  await page.getByRole('button', { name: 'Activar mi cuenta' }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('No se pudo activar')
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveValue('MiCuentaSegura123')
  expect(await page.locator('body').evaluate(el => el.scrollWidth <= window.innerWidth)).toBe(true)
})

test('confirmar un nuevo correo requiere pulsar el botón y conserva la contraseña habitual', async ({ page }) => {
  const acciones: any[] = []
  await page.route('**/api/portal/correo', r => { const b = r.request().postDataJSON(); acciones.push(b); return r.fulfill({ json: b.accion === 'verificar' ? { nombre: 'Paciente de prueba', correo: 'nuevo@example.test' } : { confirmada: true } }) })
  await page.goto('/confirmar-correo#' + 'a'.repeat(64))
  await expect(page.getByText('nuevo@example.test', { exact: true })).toBeVisible()
  expect(acciones).toHaveLength(1); expect(acciones[0].accion).toBe('verificar'); expect(page.url()).not.toContain('a'.repeat(64))
  await page.getByRole('button', { name: 'Confirmar mi nuevo correo' }).click()
  await expect(page.getByRole('heading', { name: 'Tu correo fue actualizado' })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('contraseña habitual')
  expect(acciones[1].accion).toBe('confirmar')
})
