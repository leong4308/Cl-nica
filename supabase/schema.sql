alter table public.habitaciones enable row level security;
alter table public.camas enable row level security;
alter table public.internaciones enable row level security;
alter table public.episodios_medicos enable row level security;
alter table public.ordenes_medicas enable row level security;
alter table public.catalogo_analisis enable row level security;
alter table public.solicitudes_analisis enable row level security;

drop policy if exists usuarios_self_select on public.usuarios;
create policy usuarios_self_select on public.usuarios for select to authenticated
  using (auth_user_id = (select auth.uid()));

drop policy if exists usuarios_self_update on public.usuarios;
create policy usuarios_self_update on public.usuarios for update to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

drop policy if exists pacientes_self_select on public.perfiles_pacientes;
create policy pacientes_self_select on public.perfiles_pacientes for select to authenticated
  using (usuario_id in (select id from public.usuarios where auth_user_id = (select auth.uid())));

drop policy if exists citas_authenticated_select on public.citas;
create policy citas_authenticated_select on public.citas for select to authenticated using (true);

drop policy if exists citas_authenticated_insert on public.citas;
create policy citas_authenticated_insert on public.citas for insert to authenticated with check (true);

drop policy if exists citas_authenticated_update on public.citas;
create policy citas_authenticated_update on public.citas for update to authenticated using (true) with check (true);

drop policy if exists catalogo_authenticated_select on public.catalogo_analisis;
create policy catalogo_authenticated_select on public.catalogo_analisis for select to authenticated using (true);

select table_name
from information_schema.tables
where table_schema = 'public'
  and table_name in (
    'usuarios','clinicas','perfiles_medicos','perfiles_pacientes',
    'perfiles_enfermeros','citas','expedientes','habitaciones','camas',
    'internaciones','episodios_medicos','ordenes_medicas',
    'catalogo_analisis','solicitudes_analisis'
  )
order by table_name;

