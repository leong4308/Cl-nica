create or replace function public.clinica_reclamar_telegram(p_limite integer default 25) returns table(envio_id bigint,reserva uuid,chat_id bigint,titulo text,mensaje text) language plpgsql security definer set search_path=public,pg_temp as $$
begin
 update telegram_envios set estado='fallido',codigo_error='INTENTOS_AGOTADOS' where estado='enviando' and reservado_hasta<clock_timestamp() and intentos>=5;
 -- Omite avisos vencidos, citas que ya cambiaron y cuentas desvinculadas.
 update telegram_envios e set estado='omitido',reservado_hasta=null where e.estado in('pendiente','enviando') and exists(
 select 1 from notificaciones n left join citas c on c.id=n.cita_id where n.id=e.notificacion_id and (
 not exists(select 1 from telegram_cuentas t join usuarios u on u.id=t.usuario_id where t.usuario_id=n.usuario_id and t.activo and u.esta_activo)
 or n.creado_en<clock_timestamp()-interval '48 hours'
 or (n.tipo like 'recordatorio_%' and (c.id is null or c.estado not in('pendiente','confirmada') or c.inicio<=clock_timestamp()))
 or (n.cita_id is not null and n.tipo<>'solicitud_cambio' and n.cita_version is distinct from md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.estado)))
 or (n.tipo='cita_nueva' and c.estado not in('pendiente','confirmada'))));
 return query with elegidos as (
 select e.id from telegram_envios e where e.intentos<5 and ((e.estado='pendiente' and e.proximo_intento<=clock_timestamp()) or(e.estado='enviando' and e.reservado_hasta<clock_timestamp())) order by e.id limit greatest(1,least(p_limite,100)) for update skip locked
 ), reservados as (
 update telegram_envios e set estado='enviando',intentos=e.intentos+1,arrendamiento=gen_random_uuid(),reservado_hasta=clock_timestamp()+interval '3 minutes' from elegidos s where e.id=s.id returning e.id,e.arrendamiento,e.notificacion_id
 ) select r.id,r.arrendamiento,t.chat_id,n.titulo,n.mensaje from reservados r join notificaciones n on n.id=r.notificacion_id join telegram_cuentas t on t.usuario_id=n.usuario_id and t.activo;
end $$;

create or replace function public.clinica_generar_recordatorios(p_ahora timestamptz default clock_timestamp()) returns integer language plpgsql security definer set search_path=public,pg_temp as $$
declare n integer;
begin
 insert into notificaciones(usuario_id,tipo,titulo,mensaje,cita_id,cita_inicio,cita_version,clave)
 select u.id,case when c.inicio<=p_ahora+interval '30 minutes' then 'recordatorio_30m' when c.inicio<=p_ahora+interval '2 hours' then 'recordatorio_2h' else 'recordatorio_24h' end,
 'Recordatorio de cita',format('Paciente: %s. Médico: %s. Tu cita es el %s, de %s a %s (hora de Ciudad de México). Lugar: %s. Estado: %s.',up.nombre_completo,um.nombre_completo,to_char(c.inicio at time zone 'America/Mexico_City','DD/MM/YYYY'),to_char(c.inicio at time zone 'America/Mexico_City','HH24:MI'),to_char(c.fin at time zone 'America/Mexico_City','HH24:MI'),concat_ws(' · ',cl.nombre,cl.direccion),replace(c.estado::text,'_',' ')),
 c.id,c.inicio,md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.estado)),concat('recordatorio:',c.id,':',extract(epoch from c.inicio),':',case when c.inicio<=p_ahora+interval '30 minutes' then '30m' when c.inicio<=p_ahora+interval '2 hours' then '2h' else '24h' end)
 from citas c join perfiles_pacientes p on p.id=c.paciente_id join usuarios up on up.id=p.usuario_id join perfiles_medicos m on m.id=c.medico_id join usuarios um on um.id=m.usuario_id join clinicas cl on cl.id=c.clinica_id
 join usuarios u on u.id in(p.usuario_id,m.usuario_id)
 where c.estado in('pendiente','confirmada') and c.inicio>p_ahora and c.inicio<=p_ahora+interval '24 hours' and u.esta_activo and up.esta_activo and um.esta_activo
 on conflict(usuario_id,clave) do nothing;
 get diagnostics n=row_count; return n;
end $$;


