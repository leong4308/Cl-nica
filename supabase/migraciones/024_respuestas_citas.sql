-- La versión no cambia al confirmar asistencia, pero sí ante cualquier cambio de reserva.
create function public.clinica_version_reserva(c public.citas) returns text language sql immutable set search_path=public,pg_temp as $$
 select md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.clinica_id))
$$;

-- Solo el servidor puede proporcionar un actor; el navegador usa el envoltorio con auth.uid().
create function public.clinica_responder_cita_actor(p_usuario bigint,p_cita bigint,p_version text,p_accion text,p_disponibilidad text,p_canal text) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare c citas; u usuarios; s cita_solicitudes_cambio; texto text; titulo text; clave text;
begin
 -- Mismo orden que el validador de reservas: evita interbloqueos con recepción.
 perform pg_advisory_xact_lock(37201,0);
 select * into u from usuarios where id=p_usuario and rol='paciente' and esta_activo;
 if not found then raise exception 'Cuenta de paciente sin acceso' using errcode='42501'; end if;
 select * into c from citas where id=p_cita and paciente_id in(select id from perfiles_pacientes where usuario_id=u.id and esta_activo) for update;
 if not found then raise exception 'Esta cita no pertenece a tu cuenta' using errcode='42501'; end if;
 if p_version is distinct from clinica_version_reserva(c) then raise exception 'La cita cambió. Actualiza sus detalles antes de responder' using errcode='40001'; end if;
 if p_accion not in('confirmar','cancelar','reagendar') or p_accion is null or p_canal not in('aplicacion','telegram') or p_canal is null then raise exception 'Respuesta inválida'; end if;
 if c.inicio<=clock_timestamp() then raise exception 'La cita ya comenzó. Contacta con recepción'; end if;
 if p_accion='cancelar' and c.estado='cancelada_paciente' then return jsonb_build_object('mensaje','La cita ya está cancelada.'); end if;
 if c.estado not in('pendiente','confirmada') then raise exception 'Esta cita ya no admite cambios'; end if;
 if p_accion='confirmar' then
  if c.estado='confirmada' then return jsonb_build_object('mensaje','Tu asistencia ya está confirmada.'); end if;
  update citas set estado='confirmada',actualizado_en=clock_timestamp() where id=c.id;
  texto:='Tu asistencia quedó confirmada.';
 elsif p_accion='cancelar' then
  update citas set estado='cancelada_paciente',motivo_cancelacion='Cancelación confirmada por el paciente desde '||p_canal,actualizado_en=clock_timestamp() where id=c.id;
  texto:='Tu cita quedó cancelada. Se notificó a recepción y al médico.';
 else
  if length(trim(coalesce(p_disponibilidad,''))) not between 10 and 1000 then raise exception 'Indica los días y horarios en que puedes asistir (de 10 a 1000 caracteres)'; end if;
  select * into s from cita_solicitudes_cambio where cita_id=c.id and estado='pendiente' for update;
  if found and s.disponibilidad=trim(p_disponibilidad) then return jsonb_build_object('mensaje','Recepción ya tiene tu solicitud. Tu cita actual se conserva hasta confirmar el cambio.'); end if;
  if s.id is null then
   insert into cita_solicitudes_cambio(cita_id,usuario_id,disponibilidad,canal) values(c.id,u.id,trim(p_disponibilidad),p_canal) returning * into s;
  else
   update cita_solicitudes_cambio set disponibilidad=trim(p_disponibilidad),canal=p_canal,actualizado_en=clock_timestamp() where id=s.id returning * into s;
  end if;
  clave:='solicitud-cambio:'||s.id||':'||gen_random_uuid();
  insert into notificaciones(usuario_id,tipo,titulo,mensaje,cita_id,cita_inicio,cita_version,clave)
  select id,'solicitud_cambio','Solicitud para reagendar',format('%s solicita cambiar la cita #%s del %s. Disponibilidad del paciente: %s. La cita actual se conserva hasta que recepción confirme un nuevo horario.',u.nombre_completo,c.id,to_char(c.inicio at time zone 'America/Mexico_City','DD/MM/YYYY HH24:MI'),s.disponibilidad),c.id,c.inicio,md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.estado)),clave
  from usuarios where esta_activo and (rol in('admin','recepcionista') or id=u.id);
  texto:='Tu disponibilidad se envió a recepción. Tu cita actual se conserva hasta confirmar el cambio.';
 end if;
 insert into auditoria_clinica(autor,autor_nombre,tabla,registro_id,accion,nuevo) values(u.auth_user_id,u.nombre_completo,'citas',c.id::text,'RESPUESTA_PACIENTE',jsonb_build_object('accion',p_accion,'canal',p_canal));
 return jsonb_build_object('mensaje',texto);
end $$;
revoke all on function public.clinica_responder_cita_actor(bigint,bigint,text,text,text,text) from public,anon,authenticated;
grant execute on function public.clinica_responder_cita_actor(bigint,bigint,text,text,text,text) to service_role;
create function public.clinica_responder_cita(p_cita bigint,p_version text,p_accion text,p_disponibilidad text default null) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
begin
 return clinica_responder_cita_actor((select id from usuarios where auth_user_id=auth.uid() and esta_activo),p_cita,p_version,p_accion,p_disponibilidad,'aplicacion');
end $$;
revoke all on function public.clinica_responder_cita(bigint,text,text,text) from public,anon;
grant execute on function public.clinica_responder_cita(bigint,text,text,text) to authenticated;

-- Una reserva modificada resuelve la solicitud; una cancelación la anula.
create function public.clinica_resolver_cambio_cita() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if new.estado not in('pendiente','confirmada') or clinica_version_reserva(new)<>clinica_version_reserva(old) then
  update cita_solicitudes_cambio set estado=case when new.estado in('pendiente','confirmada') then 'reagendada' else 'anulada' end,
   respuesta=case when new.estado in('pendiente','confirmada') then 'Recepción actualizó la reserva. Revisa la nueva fecha y hora en Mis citas.' else 'La cita se cerró o canceló.' end,actualizado_en=clock_timestamp()
  where cita_id=new.id and estado='pendiente';
 end if;
 return new;
end $$;
create trigger resolver_solicitud_cambio after update on public.citas for each row execute function public.clinica_resolver_cambio_cita();
create function public.clinica_reconfirmar_cambio_solicitado() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if new.estado in('pendiente','confirmada') and clinica_version_reserva(new)<>clinica_version_reserva(old)
 and exists(select 1 from cita_solicitudes_cambio where cita_id=new.id and estado='pendiente') then new.estado:='pendiente'; end if;
 return new;
end $$;
create trigger reconfirmar_cambio_solicitado before update on public.citas for each row execute function public.clinica_reconfirmar_cambio_solicitado();
revoke all on function public.clinica_reconfirmar_cambio_solicitado() from public,anon,authenticated;

create function public.clinica_listar_cambios_cita() returns jsonb language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
 if clinica_rol() is null or clinica_rol() not in('paciente','recepcionista','admin') then raise exception 'Sin acceso a solicitudes' using errcode='42501'; end if;
 return coalesce((select jsonb_agg(to_jsonb(q) order by q.actualizado_en desc) from(
  select s.*,u.nombre_completo paciente,u.telefono,c.inicio,c.fin,c.estado estado_cita,um.nombre_completo medico
  from cita_solicitudes_cambio s join citas c on c.id=s.cita_id join usuarios u on u.id=s.usuario_id join perfiles_medicos m on m.id=c.medico_id join usuarios um on um.id=m.usuario_id
  where (clinica_rol() in('admin','recepcionista') or u.auth_user_id=auth.uid()) order by s.actualizado_en desc limit 100
 ) q),'[]'::jsonb);
end $$;
create function public.clinica_cerrar_cambio_cita(p_id bigint,p_respuesta text) returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare s cita_solicitudes_cambio;
begin
 if clinica_rol() is null or clinica_rol() not in('admin','recepcionista') then raise exception 'Solo recepción y administración pueden responder' using errcode='42501'; end if;
 if length(trim(coalesce(p_respuesta,''))) not between 10 and 1000 then raise exception 'Escribe una respuesta para el paciente (10 a 1000 caracteres)'; end if;
 -- Bloquea primero la cita para coordinar la resolución con una reprogramación simultánea.
 perform 1 from citas where id=(select cita_id from cita_solicitudes_cambio where id=p_id) for update;
 update cita_solicitudes_cambio set estado='cerrada',respuesta=trim(p_respuesta),actualizado_en=clock_timestamp() where id=p_id and estado='pendiente' returning * into s;
 if not found then raise exception 'La solicitud ya fue atendida. Actualiza la lista' using errcode='40001'; end if;
 insert into notificaciones(usuario_id,tipo,titulo,mensaje,clave) values(s.usuario_id,'respuesta_cambio','Respuesta de recepción','Sobre tu solicitud de la cita #'||s.cita_id||': '||s.respuesta,'respuesta-cambio:'||s.id||':'||gen_random_uuid());
end $$;
