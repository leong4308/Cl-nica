create function public.clinica_encolar_telegram() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if exists(select 1 from telegram_cuentas where usuario_id=new.usuario_id and activo) then
  insert into telegram_envios(notificacion_id) values(new.id) on conflict do nothing;
 end if;
 return new;
end $$;
create trigger notificacion_telegram after insert on public.notificaciones for each row execute function public.clinica_encolar_telegram();

create function public.clinica_avisar_cita() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_tipo text; v_titulo text; v_texto text; v_clave text; v_paciente bigint; v_medico bigint; v_nombre text; v_doctor text; v_lugar text;
begin
 if tg_op='INSERT' then v_tipo:='cita_nueva'; v_titulo:='Nueva cita';
 elsif new.inicio is distinct from old.inicio or new.fin is distinct from old.fin or new.medico_id is distinct from old.medico_id or new.paciente_id is distinct from old.paciente_id then v_tipo:='cita_reprogramada'; v_titulo:='Cita reprogramada';
 elsif new.estado is distinct from old.estado then v_tipo:='cita_estado'; v_titulo:=case when new.estado::text like 'cancelada%' then 'Cita cancelada' when new.estado::text='confirmada' then 'Cita confirmada' when new.estado::text='atendida' then 'Consulta atendida' else 'Estado de cita actualizado' end;
 else return new; end if;
 select p.usuario_id,u.nombre_completo into v_paciente,v_nombre from perfiles_pacientes p join usuarios u on u.id=p.usuario_id where p.id=new.paciente_id;
 select m.usuario_id,u.nombre_completo into v_medico,v_doctor from perfiles_medicos m join usuarios u on u.id=m.usuario_id where m.id=new.medico_id;
 select concat_ws(' · ',nombre,direccion) into v_lugar from clinicas where id=new.clinica_id;
 v_texto:=format('Paciente: %s. Médico: %s. Fecha: %s, de %s a %s (hora de Ciudad de México). Lugar: %s. Estado: %s.',v_nombre,v_doctor,to_char(new.inicio at time zone 'America/Mexico_City','DD/MM/YYYY'),to_char(new.inicio at time zone 'America/Mexico_City','HH24:MI'),to_char(new.fin at time zone 'America/Mexico_City','HH24:MI'),v_lugar,replace(new.estado::text,'_',' '));
 v_clave:='cita:'||new.id||':'||v_tipo||':'||gen_random_uuid();
 insert into notificaciones(usuario_id,tipo,titulo,mensaje,cita_id,cita_inicio,cita_version,clave)
 select id,v_tipo,v_titulo,v_texto,new.id,new.inicio,md5(concat_ws(':',extract(epoch from new.inicio),extract(epoch from new.fin),new.medico_id,new.paciente_id,new.estado)),v_clave from usuarios where esta_activo and (id in(v_paciente,v_medico) or rol in('admin','recepcionista'));
 if tg_op='UPDATE' and old.medico_id<>new.medico_id then
  insert into notificaciones(usuario_id,tipo,titulo,mensaje,cita_id,cita_inicio,cita_version,clave)
  select usuario_id,v_tipo,'Cita reasignada a otro médico',v_texto,new.id,new.inicio,md5(concat_ws(':',extract(epoch from new.inicio),extract(epoch from new.fin),new.medico_id,new.paciente_id,new.estado)),v_clave from perfiles_medicos where id=old.medico_id on conflict do nothing;
 end if;
 return new;
end $$;
create trigger citas_notificaciones after insert or update on public.citas for each row execute function public.clinica_avisar_cita();

create function public.clinica_avisar_atencion() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_paciente bigint; v_medico bigint; v_titulo text; v_clave text;
begin
 if tg_op='UPDATE' and to_jsonb(new)=to_jsonb(old) then return new; end if;
 if tg_table_name='internaciones' then
  if tg_op='UPDATE' and new.estado=old.estado and new.medico_responsable_id=old.medico_responsable_id and new.cama_id=old.cama_id then return new; end if;
  v_paciente:=new.paciente_id; v_medico:=new.medico_responsable_id;
  v_titulo:=case when new.estado='alta' then 'Alta hospitalaria registrada' when tg_op='INSERT' then 'Ingreso hospitalario registrado' else 'Hospitalización actualizada' end;
 elsif tg_table_name='ordenes_medicas' then
  if tg_op='UPDATE' and new.estado=old.estado then return new; end if;
  select i.paciente_id,i.medico_responsable_id into v_paciente,v_medico from episodios_medicos e join internaciones i on i.id=e.internacion_id where e.id=new.episodio_id;
  v_titulo:=case when tg_op='INSERT' then 'Nueva orden médica' else 'Orden médica actualizada' end;
 else
  if tg_op='UPDATE' and new.estado=old.estado then return new; end if;
  select i.paciente_id,i.medico_responsable_id into v_paciente,v_medico from ordenes_medicas o join episodios_medicos e on e.id=o.episodio_id join internaciones i on i.id=e.internacion_id where o.id=new.orden_medica_id;
  v_titulo:=case when new.estado::text='completado' then 'Resultado de laboratorio disponible' else 'Solicitud de laboratorio actualizada' end;
 end if;
 v_clave:=tg_table_name||':'||new.id||':'||gen_random_uuid();
 insert into notificaciones(usuario_id,tipo,titulo,mensaje,clave)
 select u.id,tg_table_name,v_titulo,'Hay una actualización en la atención del paciente. Consulta los detalles en tu cuenta de Clínica Nova.',v_clave from usuarios u where u.esta_activo and (u.rol in('admin','enfermero') or u.id=(select usuario_id from perfiles_medicos where id=v_medico) or u.id=(select usuario_id from perfiles_pacientes where id=v_paciente));
 return new;
end $$;
create trigger internaciones_notificaciones after insert or update on public.internaciones for each row execute function public.clinica_avisar_atencion();
create trigger ordenes_notificaciones after insert or update on public.ordenes_medicas for each row execute function public.clinica_avisar_atencion();
create trigger laboratorio_notificaciones after insert or update on public.solicitudes_analisis for each row execute function public.clinica_avisar_atencion();

create function public.clinica_generar_recordatorios(p_ahora timestamptz default clock_timestamp()) returns integer language plpgsql security definer set search_path=public,pg_temp as $$
declare n integer;
begin
 insert into notificaciones(usuario_id,tipo,titulo,mensaje,cita_id,cita_inicio,cita_version,clave)
 select u.id,case when c.inicio<=p_ahora+interval '2 hours' then 'recordatorio_2h' else 'recordatorio_24h' end,
 'Recordatorio de cita',format('Paciente: %s. Médico: %s. Tu cita es el %s, de %s a %s (hora de Ciudad de México). Lugar: %s. Estado: %s.',up.nombre_completo,um.nombre_completo,to_char(c.inicio at time zone 'America/Mexico_City','DD/MM/YYYY'),to_char(c.inicio at time zone 'America/Mexico_City','HH24:MI'),to_char(c.fin at time zone 'America/Mexico_City','HH24:MI'),concat_ws(' · ',cl.nombre,cl.direccion),replace(c.estado::text,'_',' ')),
 c.id,c.inicio,md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.estado)),concat('recordatorio:',c.id,':',extract(epoch from c.inicio),':',case when c.inicio<=p_ahora+interval '2 hours' then '2h' else '24h' end)
 from citas c join perfiles_pacientes p on p.id=c.paciente_id join usuarios up on up.id=p.usuario_id join perfiles_medicos m on m.id=c.medico_id join usuarios um on um.id=m.usuario_id join clinicas cl on cl.id=c.clinica_id
 join usuarios u on u.id in(p.usuario_id,m.usuario_id)
 where c.estado in('pendiente','confirmada') and c.inicio>p_ahora and c.inicio<=p_ahora+interval '24 hours' and u.esta_activo and up.esta_activo and um.esta_activo
 on conflict(usuario_id,clave) do nothing;
 get diagnostics n=row_count; return n;
end $$;

create function public.clinica_confirmar_telegram(p_usuario bigint,p_vinculo uuid) returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare v telegram_vinculos;
begin
 select * into v from telegram_vinculos where id=p_vinculo and usuario_id=p_usuario for update;
 if not found or v.vence_en<=clock_timestamp() or v.chat_id is null or v.confirmado_en is not null then return false; end if;
 if not exists(select 1 from usuarios where id=p_usuario and esta_activo) then return false; end if;
 insert into telegram_cuentas(usuario_id,chat_id,nombre) values(p_usuario,v.chat_id,v.nombre)
 on conflict(usuario_id) do update set chat_id=excluded.chat_id,nombre=excluded.nombre,activo=true,vinculado_en=clock_timestamp();
 update telegram_vinculos set confirmado_en=clock_timestamp() where id=v.id;
 update telegram_vinculos set vence_en=clock_timestamp() where usuario_id=p_usuario and id<>v.id and confirmado_en is null;
 insert into telegram_envios(notificacion_id) select id from notificaciones where usuario_id=p_usuario and leida_en is null and creado_en>clock_timestamp()-interval '24 hours' and cita_inicio>clock_timestamp() on conflict do nothing;
 return true;
end $$;

create function public.clinica_reclamar_telegram(p_limite integer default 25) returns table(envio_id bigint,reserva uuid,chat_id bigint,titulo text,mensaje text) language plpgsql security definer set search_path=public,pg_temp as $$
begin
 update telegram_envios set estado='fallido',codigo_error='INTENTOS_AGOTADOS' where estado='enviando' and reservado_hasta<clock_timestamp() and intentos>=5;
 -- Omite avisos vencidos, citas que ya cambiaron y cuentas desvinculadas.
 update telegram_envios e set estado='omitido',reservado_hasta=null where e.estado in('pendiente','enviando') and exists(
 select 1 from notificaciones n left join citas c on c.id=n.cita_id where n.id=e.notificacion_id and (
 not exists(select 1 from telegram_cuentas t join usuarios u on u.id=t.usuario_id where t.usuario_id=n.usuario_id and t.activo and u.esta_activo)
 or n.creado_en<clock_timestamp()-interval '48 hours'
 or (n.tipo like 'recordatorio_%' and (c.id is null or c.estado not in('pendiente','confirmada') or c.inicio<=clock_timestamp()))
 or (n.cita_id is not null and n.cita_version is distinct from md5(concat_ws(':',extract(epoch from c.inicio),extract(epoch from c.fin),c.medico_id,c.paciente_id,c.estado)))
 or (n.tipo='cita_nueva' and c.estado not in('pendiente','confirmada'))));
 return query with elegidos as (
 select e.id from telegram_envios e where e.intentos<5 and ((e.estado='pendiente' and e.proximo_intento<=clock_timestamp()) or(e.estado='enviando' and e.reservado_hasta<clock_timestamp())) order by e.id limit greatest(1,least(p_limite,100)) for update skip locked
 ), reservados as (
 update telegram_envios e set estado='enviando',intentos=e.intentos+1,arrendamiento=gen_random_uuid(),reservado_hasta=clock_timestamp()+interval '3 minutes' from elegidos s where e.id=s.id returning e.id,e.arrendamiento,e.notificacion_id
 ) select r.id,r.arrendamiento,t.chat_id,n.titulo,n.mensaje from reservados r join notificaciones n on n.id=r.notificacion_id join telegram_cuentas t on t.usuario_id=n.usuario_id and t.activo;
end $$;

-- Solo el servidor o el proceso programado pueden generar avisos, enlazar chats y enviar.
do $$ declare r record; begin
 for r in select oid::regprocedure firma from pg_proc where pronamespace='public'::regnamespace and proname in('clinica_encolar_telegram','clinica_avisar_cita','clinica_avisar_atencion','clinica_generar_recordatorios','clinica_confirmar_telegram','clinica_reclamar_telegram') loop
 execute format('revoke all on function %s from public,anon,authenticated',r.firma); execute format('grant execute on function %s to service_role',r.firma);
 end loop;
 if exists(select 1 from pg_publication where pubname='supabase_realtime') then
  alter publication supabase_realtime add table public.notificaciones;
 end if;
end $$;
-- pg_cron crea los recordatorios aunque el portal esté cerrado. Telegram usa el trabajador documentado.
do $$ begin
 if exists(select 1 from pg_available_extensions where name='pg_cron') then
  create extension if not exists pg_cron;
  perform cron.schedule('clinica-recordatorios','*/5 * * * *','select public.clinica_generar_recordatorios()');
 end if;
end $$;
