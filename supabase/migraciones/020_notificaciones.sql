);
create table public.telegram_vinculos (
 id uuid primary key default gen_random_uuid(), usuario_id bigint not null references public.usuarios(id) on delete cascade,
 token_hash text not null unique, vence_en timestamptz not null,
 chat_id bigint, nombre text, recibido_en timestamptz, confirmado_en timestamptz
);
create table public.telegram_envios (
 id bigint generated by default as identity primary key,
 notificacion_id bigint not null unique references public.notificaciones(id) on delete cascade,
 estado text not null default 'pendiente' check(estado in ('pendiente','enviando','enviado','omitido','fallido')),
 intentos integer not null default 0, proximo_intento timestamptz not null default clock_timestamp(),
 arrendamiento uuid, reservado_hasta timestamptz, codigo_error text,
 enviado_en timestamptz
);
